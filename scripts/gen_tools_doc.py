"""Regenerate docs/tools.md from the running server's catalog.

Needs a Ghidra installation (the worker starts a JVM to report its tools):

    GHIDRA_INSTALL_DIR=/path/to/ghidra uv run python scripts/gen_tools_doc.py
"""

from __future__ import annotations

import asyncio
import os
import sys
from pathlib import Path

from fastmcp import Client
from fastmcp.client.transports import StdioTransport

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "tools.md"
INTRO = """# Tools

Generated by `scripts/gen_tools_doc.py` from the server's own catalog; do not edit.

**Listed** tools are in every client's tool list. The rest are found with
`search_tools` and called through `call`, `batch` (as an op) or `execute`
(`tools.<name>(...)`). `ghidra://api/tools.pyi` has every tool's full typed
signature and documentation.
"""


async def main() -> None:
    exe = Path(sys.executable).with_name("re-mcp-ghidra")
    full = {**os.environ, "GHIDRA_MCP_DISABLE_TOOL_SEARCH": "1"}
    async with Client(StdioTransport(str(exe), [], env=dict(os.environ))) as client:
        listed = {t.name for t in await client.list_tools()}
    async with Client(StdioTransport(str(exe), [], env=full)) as client:
        tools = await client.list_tools()

    # Without a started worker the catalog holds only the supervisor's tools;
    # writing that would silently drop most of the document.
    names = {t.name for t in tools}
    if "decompile_function" not in names or len(names) < 100:
        raise SystemExit(
            f"Catalog has {len(names)} tools and no worker tools; is GHIDRA_INSTALL_DIR "
            "set and the machine idle enough for the worker to start? docs/tools.md unchanged."
        )

    groups: dict[str, list] = {}
    for tool in sorted(tools, key=lambda t: t.name):
        if tool.name.startswith("_"):
            continue
        meta = tool.meta or {}
        tags = sorted((meta.get("fastmcp") or {}).get("tags") or ["lifecycle"])
        groups.setdefault(tags[0], []).append(tool)

    lines = [INTRO]
    for group in sorted(groups):
        lines += [f"## {group}", "", "| Tool | Listed | What it does |", "|---|---|---|"]
        for tool in groups[group]:
            first = (tool.description or "").strip().split("\n")[0].replace("|", "\\|")
            mark = "yes" if tool.name in listed else ""
            lines.append(f"| `{tool.name}` | {mark} | {first} |")
        lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({sum(len(g) for g in groups.values())} tools)")


if __name__ == "__main__":
    asyncio.run(main())
